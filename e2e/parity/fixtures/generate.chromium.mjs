#!/usr/bin/env node
/**
 * Regenerates the FROZEN `chromium-sealed.vault.js` fixture (issue #150) by sealing
 * `fixtureDocument()` with the real `frontend/js/crypto.js`, running INSIDE a real Chromium
 * page (Android's System WebView is Chromium, so this is the closest honest stand-in for
 * "device" available on this machine).
 *
 * DO NOT run this to "fix" a failing parity test — see the warning in generate.node.mjs and in
 * ../README.md; it applies here identically. Only run this deliberately, and only alongside
 * updating the README.
 *
 * Spins up the same FastAPI static server the Playwright suite uses (so `crypto.js` loads as a
 * real same-origin ES module from `/static/js/crypto.js`), seals the vault in-page, writes the
 * result, and tears the server down.
 *
 * The fixture is emitted as a plain `.js` module (`export const chromiumSealedFixture = {...}`),
 * not `.json`/`.mjs` — see the note in generate.node.mjs and ../README.md for why.
 *
 * Usage:  node e2e/parity/fixtures/generate.chromium.mjs
 */
import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
import { setTimeout as sleep } from 'node:timers/promises';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fixtureDocument, FIXTURE_PASSWORD, FIXTURE_RECOVERY_CODE } from './fixture-document.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '../../..');
const PORT = 8099; // scratch port, distinct from the Playwright suite's 8089

async function waitForServer(url, tries = 60) {
    for (let i = 0; i < tries; i++) {
        try {
            const res = await fetch(url);
            if (res.ok) return;
        } catch {
            /* not up yet */
        }
        await sleep(250);
    }
    throw new Error(`server did not come up at ${url}`);
}

async function main() {
    const python = process.platform === 'win32' ? 'python' : 'python3';
    const server = spawn(
        python,
        ['-m', 'uvicorn', 'backend.main:app', '--host', '127.0.0.1', '--port', String(PORT)],
        { cwd: REPO_ROOT, stdio: 'inherit' }
    );

    try {
        await waitForServer(`http://127.0.0.1:${PORT}/api/health`);

        const browser = await chromium.launch();
        try {
            const page = await browser.newPage();
            await page.goto(`http://127.0.0.1:${PORT}/`);

            const result = await page.evaluate(
                async ({ documentObj, password, recoveryCode }) => {
                    const mod = await import('/static/js/crypto.js');
                    const sealed = await mod.createVault(documentObj, password, {
                        recoveryCode,
                        iterations: mod.DEFAULT_ITERATIONS,
                    });
                    return { vault: sealed.vault, recoveryCode: sealed.recoveryCode };
                },
                { documentObj: fixtureDocument(), password: FIXTURE_PASSWORD, recoveryCode: FIXTURE_RECOVERY_CODE }
            );

            const userAgent = await page.evaluate(() => navigator.userAgent);

            const fixture = {
                _WARNING: 'TEST FIXTURE ONLY. Throwaway secrets, not real credentials. '
                    + 'FROZEN — see e2e/parity/README.md before editing or regenerating this file.',
                sealedBy: 'chromium',
                userAgent,
                generatedAt: new Date().toISOString(),
                password: FIXTURE_PASSWORD,
                recoveryCode: result.recoveryCode,
                document: fixtureDocument(),
                vault: result.vault,
            };

            const header = '// FROZEN TEST FIXTURE (#150) — see ../README.md before editing or regenerating this file.\n'
                + '// Do NOT regenerate this to "fix" a failing parity test: that launders exactly the kind of\n'
                + '// envelope drift this test exists to catch. Only touch this deliberately (see the README).\n'
                + '//\n'
                + '// TEST FIXTURE ONLY: the password and recovery code below are throwaway secrets that exist\n'
                + '// only to seal this frozen vault. Never real credentials.\n'
                + '//\n'
                + '// Generated by generate.chromium.mjs — do not hand-edit.\n';
            const src = `${header}export const chromiumSealedFixture = ${JSON.stringify(fixture, null, 4)};\n`;

            const out = path.join(__dirname, 'chromium-sealed.vault.js');
            writeFileSync(out, src, 'utf8');
            console.log('wrote', out);
        } finally {
            await browser.close();
        }
    } finally {
        server.kill();
    }
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
